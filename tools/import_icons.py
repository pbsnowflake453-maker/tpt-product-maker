#!/usr/bin/env python3
"""Import Picture Write icons.

Usage: python3 tools/import_icons.py <folder of downloaded images> [--size 400] [--colors 64] [--bg white|transparent] [--keep-placeholders] [--dry-run]

- Reads png/jpg/jpeg/webp/gif/svg (searches subfolders).
- File name = the word: "Cat.PNG", "cat-1.jpg", "cat (2).svg", "cat_copy.png" all become "cat".
  Names with spaces/hyphens between words become underscores ("ice cream" -> ice_cream).
  Files with no real word name (file_0000..., 1793545563922.jpg, IMG_1234) are skipped and listed.
- Each image: white background removed or kept (--bg), trimmed to the drawing, padded 6%, centered on a square, saved as
  site/images/icons/<word>.png. Duplicates: the biggest source image wins; others are listed.
- Rebuilds site/data/images.js (window.IMAGE_MAP) from the PNGs in site/images/icons/.
- Reports words that are not in any skill word list (extra), wanted words with no icon (missing), and duplicates.
Needs Pillow; SVG needs cairosvg (pip install cairosvg).
"""
import sys, os, re, json, io, argparse
from PIL import Image, ImageChops
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE=os.path.join(ROOT,'site'); OUT=os.path.join(SITE,'images','icons'); MAPJS=os.path.join(SITE,'data','images.js')
EXT={'.png','.jpg','.jpeg','.webp','.gif','.svg'}

def word_of(fn):
    b=os.path.splitext(os.path.basename(fn))[0].strip().lower()
    b=re.sub(r'\s*\(\d+\)$','',b); b=re.sub(r'[_\- ]?(copy|final|v\d+)$','',b); b=re.sub(r'[_\- ]?\d+$','',b)
    b=re.sub(r'[\s\-]+','_',b).strip('_')
    if not re.fullmatch(r'[a-z]+(_[a-z]+)*',b) or re.match(r'^(file|img|image|screenshot|photo|dsc|pxl)_',b) or len(b)<2: return None
    return b

def load(path):
    if path.lower().endswith('.svg'):
        import cairosvg
        return Image.open(io.BytesIO(cairosvg.svg2png(url=path,output_width=1200))).convert('RGBA')
    im=Image.open(path); im.seek(0) if hasattr(im,'seek') else None
    return im.convert('RGBA')

def normalize(im,size,bg):
    # make near-white pixels transparent so the drawing can be trimmed (works for white-background jpgs too)
    px=im.load(); w,h=im.size
    rgb=im.convert('RGB'); white=Image.new('RGB',im.size,(255,255,255))
    diff=ImageChops.difference(rgb,white).convert('L').point(lambda v:255 if v>18 else 0)
    alpha=ImageChops.multiply(im.getchannel('A'),diff)
    box=alpha.point(lambda v:255 if v>10 else 0).getbbox()
    if not box: return None
    im=im.crop(box); a=alpha.crop(box)
    if bg=='transparent': im.putalpha(a)
    pad=int(max(im.size)*0.06); side=max(im.size)+2*pad
    canvas=Image.new('RGBA',(side,side),(255,255,255,0 if bg=='transparent' else 255))
    canvas.alpha_composite(im if bg=='transparent' else Image.alpha_composite(Image.new('RGBA',im.size,(255,255,255,255)),im),((side-im.size[0])//2,(side-im.size[1])//2))
    return canvas.resize((size,size),Image.LANCZOS)

def enhance(im):
    # Bolder, darker lines for thin or faint drawings (mostly the JPG line art): darken grays, then thicken thin strokes.
    from PIL import ImageFilter
    rgb=im.convert('RGB'); g=rgb.convert('L')
    ink=g.point(lambda v:255 if v<170 else 0); n=sum(1 for v in ink.getdata() if v)
    if not n: return im
    kept=sum(1 for v in ink.filter(ImageFilter.MinFilter(5)).getdata() if v)
    out=rgb.point(lambda v:255 if v>235 else int(v*0.55))  # faint gray lines -> dark
    if kept/n<0.08: out=out.filter(ImageFilter.MinFilter(3))  # strokes thinner than ~2px: thicken by 1px each side
    if im.mode=='RGBA': out=out.convert('RGBA'); out.putalpha(im.getchannel('A'))
    return out

def skill_words():
    s=open(os.path.join(SITE,'data','skills.js'),encoding='utf8').read(); L=json.loads(s[s.index('['):s.rindex(']')+1])
    return {w for sk in L for w,_ in sk.get('decodable',[])}

def old_map():
    try:
        s=open(MAPJS,encoding='utf8').read(); return json.loads(s[s.index('{'):s.rindex('}')+1])
    except Exception: return {}

def write_map(keep_placeholders,wanted):
    words=sorted(os.path.splitext(f)[0] for f in os.listdir(OUT) if f.endswith('.png'))
    m={w:f'images/icons/{w}.png' for w in words}
    if keep_placeholders:
        for w in wanted:
            m.setdefault(w,None)
    hdr=('// Picture Write icons: word -> image path (generated by tools/import_icons.py from site/images/icons/).\n'
         '// null = plain placeholder box. Re-run the script after adding or removing icons.\n')
    open(MAPJS,'w',encoding='utf8').write(hdr+'window.IMAGE_MAP='+json.dumps(dict(sorted(m.items())),indent=0)+';\n')
    return m

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('src',nargs='?'); ap.add_argument('--size',type=int,default=400)
    ap.add_argument('--bg',choices=['white','transparent'],default='white'); ap.add_argument('--keep-placeholders',action='store_true'); ap.add_argument('--dry-run',action='store_true'); ap.add_argument('--no-enhance',action='store_true',help='skip darkening/thickening thin lines'); ap.add_argument('--colors',type=int,default=64,help='palette colors for smaller PNGs (0 = full color)')
    a=ap.parse_args(); os.makedirs(OUT,exist_ok=True)
    wanted=[w for w,v in old_map().items()]  # words previously listed (placeholders + icons)
    found={}; skipped=[]; dups=[]; bad=[]
    if a.src:
        for d,_,fs in os.walk(a.src):
            for f in fs:
                p=os.path.join(d,f)
                if os.path.splitext(f)[1].lower() not in EXT: continue
                w=word_of(f)
                if not w: skipped.append(os.path.relpath(p,a.src)); continue
                try: im=load(p)
                except Exception as e: bad.append(f'{os.path.relpath(p,a.src)} ({e.__class__.__name__})'); continue
                area=im.size[0]*im.size[1]
                if w in found:
                    dups.append(f'{w}: {os.path.relpath(found[w][0],a.src)} vs {os.path.relpath(p,a.src)}')
                    if area<=found[w][1]: continue
                found[w]=(p,area,im)
        for w,(p,_,im) in sorted(found.items()):
            n=normalize(im,a.size,a.bg)
            if n is None: bad.append(f'{w} (blank image)'); continue
            if not a.no_enhance: n=enhance(n)
            if a.colors: n=(n.convert('RGB').quantize(colors=a.colors,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE) if a.bg=='white' else n.quantize(colors=a.colors,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE))
            if not a.dry_run: n.save(os.path.join(OUT,w+'.png'),optimize=True)
    m=old_map() if a.dry_run else write_map(a.keep_placeholders,wanted)
    have={w for w,v in m.items() if v} | set(found)
    sw=skill_words()
    print(f'Imported {len(found)} icons ({"dry run, nothing written" if a.dry_run else OUT}). IMAGE_MAP now has {sum(1 for v in m.values() if v)} icons.')
    def lst(t,xs):
        print(f'\n{t} ({len(xs)}):'); [print('  '+x) for x in sorted(xs)[:200]]; 
        if len(xs)>200: print(f'  ... {len(xs)-200} more')
    lst('Extra: icon words not in any skill word list (Picture Write will never pick these)',[w for w in have if w not in sw])
    lst('Missing: wanted words with no icon yet',[w for w in wanted if w not in have])
    lst('Duplicates (bigger image kept)',dups)
    lst('Skipped: file name is not a word (rename to the word, e.g. cat.png)',skipped)
    lst('Could not read',bad)

if __name__=='__main__': main()
