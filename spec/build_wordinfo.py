#!/usr/bin/env python3
"""Mega Word Bank -> site/data/wordinfo.js  (run from the repo root: python3 spec/build_wordinfo.py)

Per-word facts the word-work pages need that skills.js does not carry. Source of truth: data-src/phonics_words.csv.
Output: window.WORDINFO = {
  drawable:  space-separated words a first grader can draw (the bank's drawable=yes), blocked words removed   -> Read and Draw (words)
  countable: space-separated words with 2 to 5 sounds (the Count the Sounds boxes hold 5)                        -> Count the Sounds
  tricky:    [[word, sequence], ...] base tricky words (no contractions, no names) for the tricky-word picker
  irregular: {word: "pattern"} which letters of a tricky word are the tricky ones, e.g. "n[o]"; used to choose
             which letters to blank on the Missing Letters pages (the regular letters stay visible)
}

Sound counting follows the morning-work rules: digraphs, vowel teams and doubled letters are one sound; qu and x are one sound;
a silent final e is no sound; a plural adds one sound (two for -es: boxes); -ed is one sound after /t/ or /d/ and two otherwise;
-ness and -less add three. -ing words are not used.
The count is only used to keep words that fit in 5 boxes, so a rare over-count just leaves a word out.
"""
import csv, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(ROOT, 'data-src/phonics_words.csv'), encoding='utf-8')))
for r in rows:
    r['seq'] = int(r['sequence'])

BLOCK = set("vat inn vend trump grinch hell damn slut sex butt bum kill gun jerk dumb hick hag thug crap dick cock cocks tit tits pimp prick nag slum lust sod sot wimp bust rum gin wee pee grope nude rape hoe dope nuke lube dike toot kidnap armpit spanking".split())

# letter groups that make one sound (longest match first); the second group is vowel teams that show up after Unit 3
DIG = ["tch", "sh", "ch", "th", "ck", "ng", "qu", "wh", "kn", "wr", "ee", "oo", "ou", "oi", "aw", "er", "ar", "or", "ai", "ay", "oa",
       "bb", "dd", "ff", "gg", "ll", "ss", "cc", "nn", "pp", "rr", "tt", "zz", "mm"]
TEAMS = ["igh", "dge", "ph", "ea", "ow", "oy", "ew", "ue", "ie", "ur", "ir", "au", "ey"]

def gtokens(w):
    out = []; i = 0; w = w.lower()
    while i < len(w):
        for g in ("tch", "igh", "dge"):
            if w[i:i + 3] == g: out.append(g); i += 3; break
        else:
            if w[i:i + 2] in DIG or w[i:i + 2] in TEAMS: out.append(w[i:i + 2]); i += 2
            else: out.append(w[i]); i += 1
    return out

base = [r for r in rows if r['form'] == 'base' and r['tricky'] == 'no']
SILENT_E = {r['word'] for r in base if len(gtokens(r['word'])) >= 3 and gtokens(r['word'])[-1] == 'e'}
DERIVED = {r['word']: (r['base_word'], r['form'], r['ending_sound'])
           for r in rows if r['form'] in ('-ed', '-ness', '-less', '-ing', 'plural -s') and r['base_word']}

def sounds(w):
    if w in DERIVED:
        b, form, es = DERIVED[w]
        if form == 'plural -s': return sounds(b) + (2 if es == '/ez/' else 1)      # boxes = b o x + e z
        return sounds(b) + {'-ed': 1 if es in ('/t/', '/d/') else 2, '-ness': 3, '-less': 3, '-ing': 2}[form]
    toks = gtokens(w)
    if w in SILENT_E and toks[-1] == 'e': toks = toks[:-1]
    return len(toks)

def blocked(r): return r['word'] in BLOCK or r['base_word'] in BLOCK

# -ed words that need a spelling rule that is not taught yet (hike -> hiked) stay out
norule = lambda r: r['form'] == '-ed' and r['spelling_change'] in ('dropped e', 'added k')

drawable = sorted({r['word'] for r in rows if r['drawable'] == 'yes' and r['tricky'] == 'no' and r['is_name'] == 'no'
                   and r['word'].isalpha() and not blocked(r)})
countable = sorted({r['word'] for r in rows if r['form'] in ('base', 'plural -s', '-ed', '-ness', '-less')
                    and r['tricky'] == 'no' and r['is_name'] == 'no' and r['word'].isalpha()
                    and not blocked(r) and not norule(r) and 2 <= sounds(r['word']) <= 5})
tricky = sorted({(r['word'], r['seq']) for r in rows if r['tricky'] == 'yes' and r['form'] == 'base' and r['is_name'] == 'no'},
                key=lambda x: (x[1], x[0]))
irregular = json.load(open(os.path.join(ROOT, 'data-src/tricky_irregular.json'), encoding='utf-8'))

out = {'drawable': ' '.join(drawable), 'countable': ' '.join(countable), 'tricky': [list(t) for t in tricky], 'irregular': irregular}
path = os.path.join(ROOT, 'site/data/wordinfo.js')
with open(path, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by spec/build_wordinfo.py from data-src/phonics_words.csv. Do not edit by hand.\n')
    f.write('window.WORDINFO=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('drawable %d, countable %d, tricky %d, irregular %d -> %s' % (len(drawable), len(countable), len(tricky), len(irregular), path))
